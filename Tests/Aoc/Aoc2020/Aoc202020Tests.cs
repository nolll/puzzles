    [Fact]
    public void EdgesAreCorrect()
    {
        const string input = """
                             Tile 2311:
                             ..##.#..#.
                             ##..#.....
                             #...##..#.
                             ####.#...#
                             ##.##.###.
                             ##...#.###
                             .#.#.#..##
                             ..#....#..
                             ###...#.#.
                             ..###..###
                             """;

        var tile = Aoc202020.JigsawTile.Parse(input);

        tile.Edges["top"].Should().Be("..##.#..#.");
        tile.Edges["right"].Should().Be("...#.##..#");
        tile.Edges["bottom"].Should().Be("..###..###");
        tile.Edges["left"].Should().Be(".#####..#.");
    }

    [Fact]
    public void CornerTileProductIsCorrect() => Sut.Part1(Input).Should().Be(20899048083289);

