    {
        const string input = """
                             Tile 2311:
                             ..##.#..#.
                             ##..#.....
                             #...##..#.
                             ####.#...#
                             ##.##.###.
                             ##...#.###
                             .#.#.#..##
                             ..#....#..
                             ###...#.#.
                             ..###..###
                             """;

        const string expected = """
                                #..#....
                                ...##..#
                                ###.#...
                                #.##.###
                                #...#.##
                                #.#.#..#
                                .#....#.
                                ##...#.#
                                """;

        var tile = Aoc202020.JigsawTile.Parse(input);
        tile.RemoveBorder();

        tile.Grid.Print().Should().Be(expected);
    }

